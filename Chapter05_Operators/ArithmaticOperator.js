//+, - , *, 


let a = 10;
let b = 5;          

let sum = a + b; // Addition
let subtraction = a - b; // Subtraction
let multiplication = a * b; // Multiplication           
let division = a / b; // Division
let modulus = a % b; // Modulus     
let exponentiation = a ** b; // Exponentiation

console.log("Sum: " + sum); // Output: Sum: 15

console.log("Subtraction: " + subtraction); // Output: Subtraction: 5

console.log("Multiplication: " + multiplication); // Output: Multiplication: 50         

console.log("Division: " + division); // Output: Division: 2

console.log("Modulus: " + modulus); // Output: Modulus: 0 it will give the remainder of the division

console.log("Exponentiation: " + exponentiation); // Output: Exponentiation: 100000