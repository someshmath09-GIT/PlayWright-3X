// && and -> and operator
// || or -> or operator
// ! not -> not operator    
//logical operators are used to combine two or more conditions and return a boolean value (true or false) based on the evaluation of the conditions.    

let a =true;
let b = false; 

console.log("a && b: " + (a && b)); // Output: a && b: false

console.log("a || b: " + (a || b)); // Output: a || b: true 

console.log("!a: " + !a); // Output: !a: false
