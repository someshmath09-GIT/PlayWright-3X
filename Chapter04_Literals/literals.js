let age = "somesh"; //this is string literal 
let isStudent = true; //this is boolean literal
let pi = 3.14; //this is number literal
let name = "Alice"; //this is string literal assigning a variable name with a string value Alice
let nullValue = null; //this is null literal
let undefinedValue = undefined; //this is undefined literal


console.log(typeof age); // Output: string
console.log(typeof isStudent); // Output: boolean
console.log(typeof pi); // Output: number       
console.log(typeof name); // Output: string
console.log(typeof nullValue); // Output: object (this is a known quirk in JavaScript)
console.log(typeof undefinedValue); // Output: undefined
//typeof operator is used to determine the type of a variable or value in JavaScript. It returns a string indicating the type of the operand.   
